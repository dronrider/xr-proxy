//! `xr-web`: браузерный вход к живому HTTP-сервису агента (LLD-38 фаза 2).
//!
//! Отдельный сервис, а не режим relay, и это главное решение дизайна (п. 3.1).
//! Браузер не умеет ни обфусцированный mux, ни пиннинг ключа агента, поэтому
//! TLS ему терминирует VPS, и на браузерном пути посредник видит содержимое.
//! Обещание «relay ничего не видит» от этого не размывается: relay остаётся
//! слепым и не правится ни на строчку, а плейнтекст живёт в памяти другого
//! процесса, с другим юнитом и другими правами. Пользователю это сказано прямо
//! на странице входа.
//!
//! Путь запроса: браузер приходит на `https://<имя>.<web-домен>`, фронт
//! разбирает `Host`, проверяет свою cookie-сессию, берёт маршрут публикации у
//! хаба (кеш до `exp` минус запас), открывает или переиспользует соединение до
//! агента (mux к relay плюс pinned-TLS) и проксирует запрос как пришёл, добавив
//! мандат публикации. Ответ едет обратно потоком.

