package com.xrproxy.app.service

/**
 * Чем вызван стоп туннеля - от этого зависит запись в журнале диагностики
 * (XR-221). `onRevoke()` раньше звал тот же путь, что и кнопка «Отключить»,
 * и в журнал ложилось «туннель остановлен пользователем» даже когда VPN
 * отозвала система (тумблер в настройках Android) или его перехватил другой
 * VPN-клиент - пользователь в приложении при этом ничего не нажимал, а
 * диагностика указывала на него.
 */
enum class VpnStopReason(val journalMessage: String) {
    UI("туннель остановлен пользователем"),
    SYSTEM_REVOKE(
        "VPN отозван системой: отключён в настройках Android или перехвачен другим VPN-клиентом",
    ),
}
